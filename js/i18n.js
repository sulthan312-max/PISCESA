// =====================================================
// LANGUAGE MANAGEMENT
// =====================================================

let currentLanguage = localStorage.getItem('piscesa-language') || 'id';

function setLanguage(lang) {
    if (i18n[lang]) {
        currentLanguage = lang;
        localStorage.setItem('piscesa-language', lang);
        applyTranslations();
        updatePageLang();
    }
}

function getLanguage() {
    return currentLanguage;
}

function translate(key) {
    return i18n[currentLanguage]?.[key] || i18n['id']?.[key] || key;
}

function applyTranslations() {
    document.querySelectorAll('[data-i18n]').forEach(el => {
        const key = el.getAttribute('data-i18n');
        el.textContent = translate(key);
    });
}

function updatePageLang() {
    document.documentElement.lang = currentLanguage;
}

// Initialize on page load
document.addEventListener('DOMContentLoaded', () => {
    applyTranslations();
    updatePageLang();
    updateLanguageButtons();
});

function updateLanguageButtons() {
    const idBtn = document.getElementById('langID');
    const enBtn = document.getElementById('langEN');
    
    if (idBtn) idBtn.classList.toggle('active', currentLanguage === 'id');
    if (enBtn) enBtn.classList.toggle('active', currentLanguage === 'en');
}
